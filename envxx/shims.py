"""Launcher shims that let a tool be called by name without the envxx prefix.

A shim is a tiny script in ~/.envxx/bin/ that points at an installed entry
point. Two things matter:

- the path inside the shim is relative to the shim's own location, so moving
  or copying the whole ~/.envxx directory keeps it working;
- the file name encodes which version it calls, so python3.12 and python3.11
  can both be on PATH at once without ambiguity.

Nothing here touches the system. A shim is a file inside the store, and
deleting the store deletes it.
"""
from __future__ import annotations

import os
import re
import stat
import sys
from pathlib import Path

from . import store
from .errors import UsageError

# Marks a file as ours, so --remove never deletes something a user wrote.
BAT_MARKER = "rem generated by envxx"
SH_MARKER = "# generated by envxx"


def shim_dir() -> Path:
    """Always the global store's bin, never a project one.

    A shim is a PATH entry, and PATH is a property of the machine or the
    user, not of a checkout. Pointing a project's runtime at it is fine: the
    shim names an absolute install location, so the same bin directory can
    serve every project on the machine.
    """
    return store.global_home() / "bin"


def shim_name(tool: str, version: str) -> str:
    """The command a shim answers to: 'python3.12', 'claude'.

    The version is the one the user asked for, not the resolved patch: a
    shim called python3.10.22 would have to be rebuilt on every patch
    release, while python3.10 keeps working.
    """
    if version:
        return f"{tool}{version}"
    return tool


def _target_command(provider, version: str) -> tuple[Path, list[str]]:
    """What the shim should exec, resolved the same way 'envxx <tool>' would."""
    from .run import resolve_command

    return resolve_command(provider, version)


def _relative_target(shim: Path, exe: Path, leading: list[str]) -> str:
    """Express the executable relative to the shim, with forward slashes.

    A shim is generated on one machine and used there, but the store may be
    moved to another drive or copied elsewhere; relative positioning survives
    that where an absolute path would not.
    """
    try:
        return os.path.relpath(exe, shim.parent).replace("\\", "/")
    except ValueError:
        # different volume on Windows: relpath cannot express it
        return str(exe).replace("\\", "/")


def _shim_binary() -> Path:
    """The prebuilt launcher shipped inside the package.

    A frozen PyInstaller binary unpacks its data files into sys._MEIPASS
    rather than beside the module, so both locations are tried.
    """
    here = Path(__file__).with_name("data") / "envxx-shim.exe"
    if here.is_file():
        return here

    bundled = getattr(sys, "_MEIPASS", None)
    if bundled:
        return Path(bundled) / "envxx" / "data" / "envxx-shim.exe"
    return here


def _write_exe_shim(path: Path, target: str, leading: list[str]) -> None:
    """Copy the launcher and append the target path after the PE image.

    A .bat cannot do this job: cmd.exe re-parses "%*", so an argument with a
    space arrives split. The launcher receives already-parsed argv and
    rebuilds the child command line itself, which is the only way to keep
    every argument exactly as the caller wrote it on Windows.

    QuickEdit-style wrappers also have a size limit in some cmd versions, so
    the target travels in the file rather than in an environment variable.
    """
    source = _shim_binary()
    if not source.is_file():
        raise UsageError(
            f"the shim launcher is missing from the package ({source}); "
            f"reinstall envxx"
        )

    # the target inside the binary is relative, so the whole store can move
    trailer = b"\n@@ENVXX-TARGET@@" + target.encode("utf-8") + b"\n"
    data = source.read_bytes() + trailer
    path.write_bytes(data)


def _sh_body(target: str, leading: list[str]) -> str:
    args = " ".join(leading)
    call = f'"$(dirname "$0")/{target}"'
    if args:
        call += f" {args}"
    return f'#!/bin/sh\n{SH_MARKER}\nexec {call} "$@"\n'


def _write_shim(path: Path, body: str) -> None:
    # newline="" keeps the CRLF we wrote for .bat/.cmd intact instead of
    # translating it a second time on Windows
    path.write_text(body, encoding="utf-8", newline="")
    if os.name != "nt":
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def create(provider, version: str, label: str | None = None) -> list[Path]:
    """Write every shim file this entry point needs. Returns what was made.

    'version' is the resolved patch an install lives in; 'label' is what the
    shim is called, defaulting to that version. Passing the query the user
    typed keeps the command stable across patch upgrades.
    """
    tool = provider.spec.name
    name = shim_name(tool, label if label is not None else version)
    exe, leading = _target_command(provider, version)

    folder = shim_dir()
    folder.mkdir(parents=True, exist_ok=True)
    shim = folder / name
    target = _relative_target(shim, exe, leading)

    written: list[Path] = []
    if os.name == "nt":
        # one .exe per command: Windows finds it through PATHEXT without an
        # extension, and it forwards arguments the way cmd cannot
        path = folder / f"{name}.exe"
        _write_exe_shim(path, target, leading)
        written.append(path)
    else:
        path = folder / name
        _write_shim(path, _sh_body(target, leading))
        written.append(path)
    return written


def remove(tool: str, version: str) -> list[Path]:
    """Delete this shim's files, leaving anything envxx did not write."""
    name = shim_name(tool, version)
    folder = shim_dir()
    if not folder.is_dir():
        return []

    # .bat and .cmd are what older versions wrote; .exe is the current form
    candidates = [
        folder / name,
        folder / f"{name}.exe",
        folder / f"{name}.bat",
        folder / f"{name}.cmd",
    ]
    removed: list[Path] = []
    for path in candidates:
        if not path.is_file() or not _is_ours(path):
            # a same-named file the user made is not ours to delete
            continue
        path.unlink()
        removed.append(path)
    return removed


def _is_ours(path: Path) -> bool:
    if path.suffix.lower() == ".exe":
        return _is_our_binary(path)
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:200]
    except OSError:
        return False
    return BAT_MARKER in head or SH_MARKER in head


def _is_our_binary(path: Path) -> bool:
    """An .exe shim is our launcher with a target trailer appended."""
    try:
        size = path.stat().st_size
        with path.open("rb") as handle:
            handle.seek(max(0, size - 16384))
            tail = handle.read()
    except OSError:
        return False
    return b"@@ENVXX-TARGET@@" in tail


def target_of(path: Path) -> str | None:
    """The relative target stored in a shim, whichever form it takes."""
    if path.suffix.lower() == ".exe":
        try:
            size = path.stat().st_size
            with path.open("rb") as handle:
                handle.seek(max(0, size - 16384))
                tail = handle.read()
        except OSError:
            return None
        marker = b"@@ENVXX-TARGET@@"
        if marker not in tail:
            return None
        found = tail.rindex(marker) + len(marker)
        return tail[found:].split(b"\n", 1)[0].decode("utf-8", "replace") or None

    try:
        body = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    match = re.search(r'%~dp0([^"]+)"|dirname \"\$0\"/([^"]+)"', body)
    if not match:
        return None
    return match.group(1) or match.group(2)


def existing() -> list[Path]:
    """Every shim currently in the bin directory."""
    folder = shim_dir()
    if not folder.is_dir():
        return []
    return sorted(p for p in folder.iterdir() if p.is_file() and _is_ours(p))


def require_installed(provider, version: str | None) -> str:
    """Resolve which installed version a shim should point at."""
    from .versions import best_match, version_key

    installed = store.installed_versions(
        provider.spec.name,
        kind=provider.spec.kind,
        scoped=provider.spec.kind == "runtime" and store.project_store() is not None,
    )
    if not installed:
        raise UsageError(f"no {provider.spec.name} versions installed")

    resolved = best_match(installed, version) if version else max(
        installed, key=version_key
    )
    if not resolved:
        raise UsageError(f"{provider.spec.name} {version} is not installed")
    return resolved
